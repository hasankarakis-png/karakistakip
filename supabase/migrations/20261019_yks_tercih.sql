create table if not exists public.yks_programs (
  id bigint generated by default as identity primary key,
  program_code text not null,
  university text not null,
  department text not null,
  city text not null,
  score_type text not null check (score_type in ('SAY','EA','SÖZ','DİL','TYT')),
  quota integer check (quota is null or quota >= 0),
  fee_type text,
  university_type text,
  language text,
  year integer not null check (year between 2010 and 2100),
  base_rank integer check (base_rank is null or base_rank > 0),
  base_score numeric(8,3),
  source_url text,
  updated_by uuid references public.profiles(id),
  updated_at timestamptz not null default now(),
  unique(program_code, year)
);
create index if not exists yks_programs_search_idx on public.yks_programs(year desc, score_type, city);
create index if not exists yks_programs_rank_idx on public.yks_programs(base_rank);
alter table public.yks_programs enable row level security;
drop policy if exists "yks_programs_authenticated_read" on public.yks_programs;
create policy "yks_programs_authenticated_read" on public.yks_programs for select to authenticated using (true);
drop policy if exists "yks_programs_coach_insert" on public.yks_programs;
create policy "yks_programs_coach_insert" on public.yks_programs for insert to authenticated with check (public.is_coach() and updated_by = auth.uid());
drop policy if exists "yks_programs_coach_update" on public.yks_programs;
create policy "yks_programs_coach_update" on public.yks_programs for update to authenticated using (public.is_coach()) with check (public.is_coach());
drop policy if exists "yks_programs_coach_delete" on public.yks_programs;
create policy "yks_programs_coach_delete" on public.yks_programs for delete to authenticated using (public.is_coach());

create table if not exists public.yks_preferences (
  id bigint generated by default as identity primary key,
  student_id uuid not null references public.profiles(id) on delete cascade,
  program_id bigint not null references public.yks_programs(id) on delete cascade,
  preference_order integer not null check (preference_order between 1 and 24),
  created_at timestamptz not null default now(),
  unique(student_id, program_id)
);
create index if not exists yks_preferences_student_idx on public.yks_preferences(student_id, preference_order);
alter table public.yks_preferences enable row level security;
drop policy if exists "yks_preferences_student_select" on public.yks_preferences;
create policy "yks_preferences_student_select" on public.yks_preferences for select to authenticated using (student_id = auth.uid() or public.is_coach());
drop policy if exists "yks_preferences_student_insert" on public.yks_preferences;
create policy "yks_preferences_student_insert" on public.yks_preferences for insert to authenticated with check (student_id = auth.uid());
drop policy if exists "yks_preferences_student_update" on public.yks_preferences;
create policy "yks_preferences_student_update" on public.yks_preferences for update to authenticated using (student_id = auth.uid() or public.is_coach()) with check (student_id = auth.uid() or public.is_coach());
drop policy if exists "yks_preferences_student_delete" on public.yks_preferences;
create policy "yks_preferences_student_delete" on public.yks_preferences for delete to authenticated using (student_id = auth.uid() or public.is_coach());

