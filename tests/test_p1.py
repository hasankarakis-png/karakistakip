# v3.7 · Profil, gün sonu ekranı, kurulum sihirbazı, uzun sayaç, Aksiyon Merkezi birleşimi
import sys, subprocess, time
from playwright.sync_api import sync_playwright
exec(open("test_nav.py").read().split("with sync_playwright() as p:")[0].replace('srv = subprocess.Popen', 'srv = None and subprocess.Popen'))
srv = subprocess.Popen([sys.executable, "-m", "http.server", "8773", "--bind", "127.0.0.1"], cwd=ROOT, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL); time.sleep(1)
URL = "http://127.0.0.1:8773/index.html"
errs = []
W = lambda page: page.evaluate("[document.documentElement.scrollWidth,innerWidth]")
with sync_playwright() as p:
    b = p.chromium.launch()
    # ---------- ÖĞRENCİ ----------
    ctx = b.new_context(viewport={"width": 390, "height": 844}, service_workers="block", device_scale_factor=2)
    ctx.add_init_script("window.__ONB=1")  # sihirbaz kendiliğinden açılsın
    setup(ctx, "student")
    page = ctx.new_page(); page.on("pageerror", lambda e: errs.append(str(e))); page.on("dialog", lambda d: d.accept())
    page.goto(URL); page.wait_for_selector(".pill"); page.wait_for_timeout(5600)
    E = page.evaluate
    E("render()"); wait(page)
    check("Felsefe" in E("SUBJ") and "Fen Bilimleri" not in E("SUBJ"), "YKS öğrencisinin ders listesi (Felsefe var, Fen Bilimleri yok)")
    check(E("PUSHON") == "no" and page.query_selector(".qa.onb") is not None, "Bildirimi kapalı öğrenciye kurulum sihirbazı kendiliğinden açıldı")
    t = txt(page, ".qa.onb")
    check("Ana ekrana ekle" in t and "Bildirimleri aç" in t, "Sihirbazda iki adım var")
    page.screenshot(path=f"{SHOTS}/p1-sihirbaz.png")
    page.click("#onbdone"); wait(page)
    check(page.query_selector(".qa.onb") is None and page.query_selector("#onbopen") is not None, "Daha sonra: sihirbaz kapandı, ana sayfada 'Kurulumu tamamla' kartı kaldı")
    E("ONB.auto=false;render()"); wait(page)
    check(page.query_selector(".qa.onb") is None, "Ertelenen sihirbaz 3 gün dolmadan tekrar açılmıyor")
    page.click("#onbopen"); wait(page)
    check(page.query_selector(".qa.onb") is not None, "Karttan sihirbaz yeniden açılıyor")
    page.go_back(); wait(page)
    check(page.query_selector(".qa.onb") is None, "Geri tuşu sihirbazı kapatıyor")

    # gün sonu ekranı
    E("S.qs=[];S.subt={Fizik:3600000};S.done=60*60000;S.mood=0;save();render()"); wait(page)
    page.click("[data-a='close']"); wait(page)
    check(page.query_selector(".qa.dc") is not None and E("S.status") != "closed", "Günü kapat: önce gün sonu ekranı açılıyor, gün henüz kapanmadı")
    rows = E("[...document.querySelectorAll('.qa.dc .dc-r b')].map(x=>x.textContent)")
    check(rows[:2] == ["Matematik", "Fizik"], f"Bugün çalışılan dersler listede (açık ders önce): {rows}")
    page.screenshot(path=f"{SHOTS}/p1-gunsonu.png")
    page.click("#dcok"); wait(page)
    check("Soru sayılarını gir" in txt(page, ".qa.dc") and E("S.status") != "closed", "Çalışıp soru girmeyen öğrenci uyarı alıyor, gün kapanmıyor")
    page.fill("#dcn0", "40"); page.fill("#dcc0", "50"); page.click("#dcok"); wait(page)
    check("doğru sayısı" in txt(page, ".qa.dc"), "Doğru > çözülen engelleniyor")
    page.fill("#dcc0", "30"); page.fill("#dcn1", "20")
    page.click("[data-dcm='4']"); wait(page)
    check(E("document.getElementById('dcn0').value") == "40" and E("document.getElementById('dcn1').value") == "20", "Puan seçince yazılan sayılar korunuyor")
    page.fill("#dcnext", "30 paragraf"); E("render()"); wait(page)
    check(E("document.getElementById('dcnext').value") == "30 paragraf", "Arka plan yeniden çiziminde yazılan korunuyor")
    page.click("#dcok"); wait(page, 500)
    check(E("S.status") == "closed", "Gün kapandı")
    check(E("S.qs.map(q=>q.s+':'+q.n+':'+q.c).join(',')") == "Matematik:40:30,Fizik:20:0", "Sorular derslere göre kaydedildi")
    check(E("S.mood") == 4 and E("S.next") == "30 paragraf", "Gün puanı ve 'yarın ilk iş' kaydedildi")
    check(E("JSON.parse(localStorage.getItem('karakis-next-s1')).t") == "30 paragraf", "Not ertesi gün için cihazda saklandı")
    check(page.query_selector(".utoast") is not None or "Geri al" in page.inner_text("body"), "Kapatma geri alınabilir (ikinci şans)")
    # ertesi gün notu
    E("localStorage.setItem('karakis-next-s1',JSON.stringify({d:dayN(-1),t:'Türev tekrarı'}));S.status='stopped';render()"); wait(page)
    check("Türev tekrarı" in txt(page, ".nn"), "Dünkü 'yarın ilk iş' notu ana sayfada")
    page.click("#nnx"); wait(page)
    check(page.query_selector(".nn") is None, "Not kapatılabiliyor")
    # soru çözmedim
    E("S.qs=[];S.status='stopped';S.done=50*60000;S.cur=null;S.subt={Tarih:3000000};save();render()"); wait(page)
    page.click("[data-a='close']"); wait(page)
    page.check("#dcnq"); page.click("#dcok"); wait(page)
    check(E("S.status") == "closed" and E("S.noq") is True and E("snap().nq") == 1, "'Bugün soru çözmedim' ile gün kapandı ve kayda işlendi")
    # soru girmeden 30 dk'dan az çalışan zorlanmıyor
    E("S.qs=[];S.status='stopped';S.done=10*60000;S.noq=false;save();render()"); wait(page)
    page.click("[data-a='close']"); wait(page); page.click("#dcok"); wait(page)
    check(E("S.status") == "closed", "Kısa çalışma gününde soru zorunlu değil")

    # uzun açık sayaç
    E("S.status='study';S.cur={start:Date.now()-4*3600e3,brk:0,bs:0,subj:'Kimya',meth:'Soru çözme'};S.done=0;S.subt={};save();render()"); wait(page)
    check(page.query_selector(".long-c") is not None, "4 saatlik açık sayaçta düzeltme kartı çıktı")
    page.screenshot(path=f"{SHOTS}/p1-uzunsayac.png")
    fut = E("(()=>{const d=new Date(Date.now()+3600e3);return String(d.getHours()).padStart(2,'0')+':'+String(d.getMinutes()).padStart(2,'0')})()")
    past = E("(()=>{const d=new Date(Date.now()-3600e3);return String(d.getHours()).padStart(2,'0')+':'+String(d.getMinutes()).padStart(2,'0')})()")
    if E("new Date().getHours()") not in (0, 23):
        page.fill("#lfix", fut); page.click("#lfixok"); wait(page)
        check("İleri bir saat" in txt(page, ".long-c"), "İleri saat seçilemiyor")
        page.fill("#lfix", past); page.click("#lfixok"); wait(page)
        m = E("Math.round(S.done/60000)")
        check(E("S.status") == "stopped" and 175 <= m <= 182, f"Süre bırakılan saate göre düzeltildi (~180 dk): {m}")
        check(E("Math.round((S.subt.Kimya||0)/60000)") == m, "Ders bazında süreye de işlendi")
        check("Süre düzeltildi" in E("S.log.map(l=>l.m).join('|')"), "Akışa düzeltme kaydı düştü")
    else:
        print("ATLANDI  uzun sayaç saat testi (gece yarısı yakını)")

    # LGS öğrencisi
    E("PROF[ME]={exam:'LGS'};subjApply();EXCAL=[];S=fresh();render()"); wait(page)
    check("Fen Bilimleri" in E("SUBJ") and "Geometri" not in E("SUBJ"), "LGS öğrencisinin ders listesi")
    body = page.inner_text(".stu-main")
    check("LGS 2027" in body and "Tarih bekleniyor" in body and "YKS 2027" not in body, "LGS geri sayımı: tarih açıklanmadıysa bekleniyor yazıyor")
    check("LGS son net" in body and "TYT son net" not in body, "Net kartı LGS'ye göre")
    E("EXCAL=[{exam_type:'LGS',exam_date:'2027-06-13'}];render()"); wait(page)
    check("13 Haziran 2027" in page.inner_text(".stu-main") and page.query_selector("#cd0") is not None, "Koç tarihi girince LGS geri sayımı başlıyor")
    check(W(page)[0] == 390, f"Öğrenci ekranında yatay taşma yok {W(page)}")
    ctx.close()

    # ---------- KOÇ ----------
    ctx = b.new_context(viewport={"width": 390, "height": 844}, service_workers="block", device_scale_factor=2); setup(ctx, "coach")
    page = ctx.new_page(); page.on("pageerror", lambda e: errs.append(str(e))); page.on("dialog", lambda d: d.accept())
    page.goto(URL); page.wait_for_selector(".kst"); page.wait_for_timeout(4700)
    E = page.evaluate
    ac = txt(page, ".coach-action-center")
    check("3 öğrencide bildirim kapalı" in ac, "Aksiyon Merkezi: bildirimi kapalı öğrenci sayısı")
    check("son 7 günde görev atanmadı" in ac, "Aksiyon Merkezi: görevsiz öğrenci sinyali")
    check(page.query_selector(".coach-action-center .ci-panel") is not None, "Telafi planı kartı Aksiyon Merkezi'nde")
    check(page.query_selector(".coach-action-center .ci-stats") is None, "Tekrarlanan sayı kutuları kaldırıldı")
    page.screenshot(path=f"{SHOTS}/p1-aksiyon.png", full_page=True)
    E("CPG='t';render()"); wait(page)
    check(page.query_selector(".ci-panel") is None, "Görev yönetimi sayfasında ikinci kopya yok")
    E("CPG='o';render()"); wait(page)
    check(E("flags([{m:60,q:0},{m:60,q:0},{m:60,q:0},{m:0,q:0},{m:50,q:10},{m:60,q:0},{m:0,q:0}]).join('|')").find("Son 5 günün 3'ünde soru sayısı girilmedi") >= 0, "Uyarı: soru girilmeyen günler")
    check(E("flags([{m:60,q:0,nq:1},{m:60,q:0,nq:1},{m:60,q:0},{m:0,q:0},{m:50,q:10},{m:60,q:0},{m:0,q:0}]).join('|')").find("soru sayısı") < 0, "'Soru çözmedim' diyen günler uyarı saymıyor")
    check(E("['KİMYA','Fizik/TARİH','Türkçe/SOSYAL','_=*9089787','Matematik-1','TYT Türkçe'].map(subjNorm).join(',')") == "Kimya,Fizik/Tarih,Türkçe/Sosyal,Diğer,Matematik-1,TYT Türkçe", "Ders adları standartlaşıyor")
    # profil
    E("openStu('s1','o')"); wait(page, 500)
    check("YKS" in txt(page, ".pr-line") and "SAY" in txt(page, ".pr-line") and "12. sınıf" in txt(page, ".pr-line") and "Tıp" in txt(page, ".pr-line"), "Öğrenci sayfasında profil satırı")
    check("Bildirim kapalı" not in txt(page, ".pr-line"), "Bildirimi açık öğrencide uyarı yok")
    E("openStu('s2','o')"); wait(page, 500)
    check("Bildirim kapalı" in txt(page, ".pr-line"), "Bildirimi kapalı öğrencide 🔕 uyarısı")
    E("DTAB='d';render()"); wait(page)
    check(page.query_selector("#detail-profile") is not None, "Diğer sekmesinde profil kartı")
    page.select_option("#prx", "LGS"); wait(page)
    check(page.query_selector("#prl") is not None and page.query_selector("#prf") is None, "LGS seçince alan gizlenip LGS tarihi alanı çıkıyor")
    page.select_option("#prg", "8"); page.fill("#prs", "Kayapınar Ortaokulu"); page.fill("#prt", "Fen lisesi"); page.fill("#prl", "2027-06-13")
    E("render()"); wait(page)
    check(E("document.getElementById('prs').value") == "Kayapınar Ortaokulu", "Arka plan çiziminde profil taslağı korunuyor")
    page.click("[data-prsave='s2']"); wait(page, 500)
    row = E("__FX.student_profile.find(r=>r.student_id==='s2')")
    check(row and row["exam"] == "LGS" and row["grade"] == "8" and row["school"] == "Kayapınar Ortaokulu" and row["field"] is None, f"Profil kaydedildi: {row}")
    check(E("__FX.exam_calendar.some(r=>r.exam_type==='LGS'&&r.exam_date==='2027-06-13')"), "LGS tarihi takvime yazıldı")
    check("Kaydedildi" in txt(page, "#detail-profile"), "Kaydedildi mesajı")
    page.screenshot(path=f"{SHOTS}/p1-profil.png", full_page=True)
    check(W(page)[0] == 390, f"Koç ekranında yatay taşma yok {W(page)}")
    E("sel=null;CPG='y';render()"); wait(page)
    check("8 haneli PIN" in E("document.body.textContent"), "Yeni öğrenci kartı 8 haneli PIN diyor")
    ctx.close()

    # masaüstü genel bakış
    ctx = b.new_context(viewport={"width": 1440, "height": 900}, service_workers="block"); setup(ctx, "coach")
    page = ctx.new_page(); page.on("pageerror", lambda e: errs.append(str(e)))
    page.goto(URL); page.wait_for_selector(".kst"); page.wait_for_timeout(4700)
    page.screenshot(path=f"{SHOTS}/p1-masaustu.png", full_page=True)
    check(W(page)[0] == 1440, f"Masaüstünde yatay taşma yok {W(page)}")
    ctx.close(); b.close()
srv.terminate()
