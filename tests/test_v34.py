    check("Hemen bakıyorum Harika gidiyorsun" in th, "Mesaj gönderildi ve akışta görünüyor")
    check(E("document.getElementById('minp').value") == "", "Gönderince yazma alanı temizlendi")
    page.screenshot(path=f"{SHOTS}/v34-sohbet.png")
    check(W(page)[0] == 390, f"Sohbette yatay taşma yok {W(page)}")
