    page.click("#minp"); page.keyboard.type("Hemen bakıyorum")
    E("msgLive({eventType:'INSERT',new:{id:99,student_id:'s2',from_coach:false,body:'Bir de fizik soruları zor geldi',created_at:new Date().toISOString(),read_at:null,kind:'chat'}})"); wait(page, 300)
    check("fizik soruları" in page.inner_text("#mth"), "Yazarken gelen yeni mesaj anında göründü")
    check(E("document.getElementById('minp').value") == "Hemen bakıyorum" and E("document.activeElement.id") == "minp", "Yazılan taslak ve odak korunuyor")
